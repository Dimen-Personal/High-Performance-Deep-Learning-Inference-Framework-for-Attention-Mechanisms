#include "cuda/cuda_ops.cuh"

#include <cuda_runtime.h>
#include <iostream>
#include <vector>
#include <random>
#include <iomanip>

float benchmark_single_block(
    const float* d_scores,
    float* d_weights,
    int seq_len,
    int warmup_runs,
    int benchmark_runs
){
    for(int i = 0; i < warmup_runs; i++)
        cuda_attention_softmax(d_scores, d_weights, seq_len);

    cudaDeviceSynchronize();



    cudaEvent_t start;
    cudaEvent_t stop;

    cudaEventCreate(&start);
    cudaEventCreate(&stop);


    cudaEventRecord(start);

    for(int i = 0; i < benchmark_runs; i++)
        cuda_attention_softmax(d_scores, d_weights, seq_len);

    cudaEventRecord(stop);
    cudaEventSynchronize(stop);



    float elapsed_ms = 0.0f;
    cudaEventElapsedTime(&elapsed_ms, start, stop);


    cudaEventDestroy(start);
    cudaEventDestroy(stop);

    return elapsed_ms / benchmark_runs;

}




float benchmark_multi_block(
    const float* d_scores,
    float* d_weights,

    float* d_partial_max,
    float* d_partial_sum,
    float* d_row_max,
    float* d_row_sum,

    int seq_len,
    int blocks_per_row,
    int warmup_runs,
    int benchmark_runs
){
    for(int i = 0; i < warmup_runs; i++)
        cuda_attention_softmax_multiblock(
            d_scores,
            d_weights,
            d_partial_max,
            d_partial_sum,
            d_row_max,
            d_row_sum,
            seq_len,
            blocks_per_row
        );

    cudaDeviceSynchronize();


    cudaEvent_t start;
    cudaEvent_t stop;
    
    cudaEventCreate(&start);
    cudaEventCreate(&stop);


    cudaEventRecord(start);
    for(int i = 0; i < benchmark_runs; i++)
        cuda_attention_softmax_multiblock(
            d_scores,
            d_weights,
            d_partial_max,
            d_partial_sum,
            d_row_max,
            d_row_sum,
            seq_len,
            blocks_per_row
        );

    cudaEventRecord(stop);
    cudaEventSynchronize(stop);


    float elapsed_ms = 0.0f;

    cudaEventElapsedTime(&elapsed_ms, start, stop);


    cudaEventDestroy(start);
    cudaEventDestroy(stop);


    return elapsed_ms / benchmark_runs;
}



