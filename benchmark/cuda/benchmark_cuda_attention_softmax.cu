int main()
{
    const int warmup_runs = 20;
    const int benchmark_runs = 100;

    const int blocks_per_row = 4;


    std::vector<int> seq_lengths = {
        128,
        256,
        512,
        1024,
        2048,
        4096,
        8192,
        12000
    };


    std::cout
        << std::left
        << std::setw(12)
        << "seq_len"

        << std::setw(20)
        << "single_ms"

        << std::setw(20)
        << "multi_ms"

        << std::setw(15)
        << "speedup"

        << std::endl;



    for(int seq_len : seq_lengths)
    {
        const std::size_t elements =
            static_cast<std::size_t>(
                seq_len
            ) * seq_len;

        const std::size_t matrix_bytes =
            elements * sizeof(float);


        const std::size_t partial_bytes =
            static_cast<std::size_t>(
                seq_len * blocks_per_row
            ) * sizeof(float);


        const std::size_t row_bytes =
            static_cast<std::size_t>(
                seq_len
            ) * sizeof(float);



        std::vector<float> scores(elements);


        std::mt19937 generator(42);

        std::uniform_real_distribution<float>
            distribution(-5.0f, 5.0f);


        for(float& value : scores)
        {
            value =
                distribution(generator);
        }



        float* d_scores = nullptr;

        float* d_single_weights = nullptr;
        float* d_multi_weights = nullptr;

        float* d_partial_max = nullptr;
        float* d_partial_sum = nullptr;

        float* d_row_max = nullptr;
        float* d_row_sum = nullptr;



        cudaMalloc(
            &d_scores,
            matrix_bytes
        );

        cudaMalloc(
            &d_single_weights,
            matrix_bytes
        );

        cudaMalloc(
            &d_multi_weights,
            matrix_bytes
        );


        cudaMalloc(
            &d_partial_max,
            partial_bytes
        );

        cudaMalloc(
            &d_partial_sum,
            partial_bytes
        );

        cudaMalloc(
            &d_row_max,
            row_bytes
        );

        cudaMalloc(
            &d_row_sum,
            row_bytes
        );



        cudaMemcpy(
            d_scores,
            scores.data(),
            matrix_bytes,
            cudaMemcpyHostToDevice
        );



        const float single_ms =
            benchmark_single_block(
                d_scores,
                d_single_weights,
                seq_len,
                warmup_runs,
                benchmark_runs
            );


        const float multi_ms =
            benchmark_multi_block(
                d_scores,
                d_multi_weights,

                d_partial_max,
                d_partial_sum,

                d_row_max,
                d_row_sum,

                seq_len,
                blocks_per_row,

                warmup_runs,
                benchmark_runs
            );



        const float speedup =
            single_ms / multi_ms;



        std::cout
            << std::left
            << std::setw(12)
            << seq_len

            << std::setw(20)
            << single_ms

            << std::setw(20)
            << multi_ms

            << std::setw(15)
            << speedup

            << std::endl;



        cudaFree(d_scores);

        cudaFree(d_single_weights);
        cudaFree(d_multi_weights);

        cudaFree(d_partial_max);
        cudaFree(d_partial_sum);

        cudaFree(d_row_max);
        cudaFree(d_row_sum);
    }


    return 0;
}
 
